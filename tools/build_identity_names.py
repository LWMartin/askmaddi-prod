#!/usr/bin/env python3
"""Project the contamination registry's product NAMES into data/identity_names.json.

WHY. A demand mint decides "new product or existing card?" in
slug_normalizer.resolve_slug, which until 2026-11-23 knew an existing card only
by its exact vendor+model. Demand for "Ulanzi F38" (ulanzif38) did not match
the card whose model is "F38 / Zero" (ulanzif38zero), so it minted the twin
ulanzi-f38, which was built, reviewed and delisted (11-19). The system's ONE
declaration of what names a product is the contamination registry
(phantom-ops fixtures/manifests/contamination.json): `self.aliases` are a
product's strict own names, `relevance.aliases` lenient forms that a sibling may
share ('ulanzi f38' is lenient for the Zero F38 because the F38 Video tripod
shares the F38 system).

WHY A COPY. The gateway runs as askmaddi and cannot read the registry (0700
under phantomops on the box), and a cross-repo import in the gateway is the
liability slug_common was created to avoid (2026-06-24). Same pattern: an
in-repo projection, guarded by test_identity_names.py's agreement test, which
regenerates from the phantom-ops registry wherever both repos are present and
fails if the committed file differs. Re-run this tool whenever the registry
changes:

    python3 tools/build_identity_names.py \\
        ../phantom-ops/claude/workspace/aggregator-build/fixtures/manifests/contamination.json
    cat contamination.json | python3 tools/build_identity_names.py -   # stdin

What is projected: for every registry product except brand-level entries
(key ending '-generic': their aliases name a maker, not a product) and
'auto' self aliases (derived at gate load time; not a declared name), the
vendor and the normalized strict and lenient names. Normalization is
slug_common._norm (identical to classifier_extract._norm_match). Names under 4
normalized characters are dropped, the registry's own floor for matching.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'gateway'))
from slug_common import _norm  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / 'data' / 'identity_names.json'
MIN_NAME = 4


def _names(aliases):
    if not isinstance(aliases, list):
        return []
    return sorted({n for n in (_norm(str(a)) for a in aliases) if len(n) >= MIN_NAME})


def project(registry):
    products = {}
    for key, e in sorted((registry.get('products') or {}).items()):
        if key.endswith('-generic'):
            continue
        strict = _names((e.get('self') or {}).get('aliases'))
        lenient = [n for n in _names((e.get('relevance') or {}).get('aliases'))
                   if n not in strict]
        if not strict and not lenient:
            continue
        products[key] = {'vendor': e.get('vendor') or '', 'strict': strict,
                         'lenient': lenient}
    return {
        '_description': ('Generated by tools/build_identity_names.py from the '
                         'contamination registry. Do not edit by hand; re-run the '
                         'tool after any registry change.'),
        'registry_version': registry.get('version'),
        'products': products,
    }


def render(registry):
    return json.dumps(project(registry), indent=1, ensure_ascii=False, sort_keys=True) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('registry', help="contamination.json path, or '-' for stdin")
    ap.add_argument('--out', default=str(OUT))
    ap.add_argument('--check', action='store_true',
                    help='exit 1 if --out differs from a fresh projection; write nothing')
    args = ap.parse_args(argv)
    raw = sys.stdin.read() if args.registry == '-' else Path(args.registry).read_text(encoding='utf-8')
    text = render(json.loads(raw))
    out = Path(args.out)
    if args.check:
        same = out.is_file() and out.read_text(encoding='utf-8') == text
        print('identity_names: up to date' if same else 'identity_names: STALE — re-run without --check')
        return 0 if same else 1
    out.write_text(text, encoding='utf-8')
    n = len(json.loads(text)['products'])
    print(f'wrote {out} ({n} products, registry {json.loads(raw).get("version")})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
